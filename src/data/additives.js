/**
 * IngrediScan additive database.
 *
 * Each entry:
 *   code      – EU E-number as used in this app ("E150d", "E407a", "E471")
 *   category  – colour | preservative | antioxidant | sweetener | emulsifier |
 *               thickener | enhancer | acid | other
 *   level     – high | medium | low | none   (how much attention it deserves,
 *               NOT a statement that the additive is illegal or unsafe at
 *               permitted levels – every additive here except E171 is
 *               authorised in the EU under Regulation (EC) 1333/2008)
 *   name      – { en, ro } display name
 *   aliases   – names as written on labels (RO + EN). Matching is done on
 *               normalised text (lowercase, no diacritics). Aliases written in
 *               ALL CAPS (e.g. "BHA", "MSG") only match as standalone capitals.
 *   why       – { en, ro } one or two factual sentences, citing EFSA,
 *               Regulation (EC) 1333/2008, IARC or the US FDA.
 *
 * Wording is deliberately cautious: where evidence is limited it says so.
 */

