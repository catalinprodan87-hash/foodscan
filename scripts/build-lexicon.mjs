#!/usr/bin/env node
/**
 * Builds src/data/lexicon-ro.js from bench/corpus/ro-ingredients.jsonl: the
 * words of real Romanian ingredient lists, used by the OCR clean-up to fix
 * one-letter slips and restore diacritics (ă â î ș ț – the recogniser cannot
 * read them). Run by hand after build-corpus.mjs:  node scripts/build-lexicon.mjs
 *
 * A word is kept when it appears at least MIN_COUNT times; its spelling is the
 * most frequent one WITH diacritics when that is used at least a fifth of the
 * time (Open Food Facts contributors often type without them), otherwise the
 * most frequent one. Words in the app's own list (lexicon.js) keep that spelling.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalize } from '../src/lib/analyze.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const MIN_COUNT = 3;
const lines = readFileSync(join(root, 'bench', 'corpus', 'ro-ingredients.jsonl'), 'utf8').split('\n').filter(Boolean);
const header = JSON.parse(lines[0]);
const texts = lines.slice(1).map((l) => JSON.parse(l).text);

const counts = new Map(); // key → Map(spelling → n)
for (const text of texts) {
  for (const raw of text.match(/\p{L}+(?:-\p{L}+)*/gu) || []) {
    for (const part of raw.split('-')) {
      if (part.length < 3 || part === part.toUpperCase() && part.length > 1 && /\p{Lu}/u.test(part) && part.length <= 4) continue; // short codes / acronyms
      const word = part.toLowerCase();
      const key = normalize(word);
      if (!/^[a-z]+$/.test(key)) continue; // other alphabets
      if (!counts.has(key)) counts.set(key, new Map());
      const m = counts.get(key);
      m.set(word, (m.get(word) || 0) + 1);
    }
  }
}

const ranked = [];
for (const [key, spellings] of counts) {
  const total = [...spellings.values()].reduce((a, b) => a + b, 0);
  if (total < MIN_COUNT) continue;
  const sorted = [...spellings].sort((a, b) => b[1] - a[1]);
  const withDiacritics = sorted.find(([w]) => w !== key);
  const pick = withDiacritics && withDiacritics[1] >= total / 5 ? withDiacritics[0] : sorted[0][0];
  ranked.push([pick, total]);
}
// Most frequent first: the clean-up uses the order to break ties between candidates.
ranked.sort((a, b) => b[1] - a[1] || normalize(a[0]).localeCompare(normalize(b[0])));
const words = ranked.map(([w]) => w);

const out = `/**
 * Romanian ingredient words from real labels (Open Food Facts, products sold
 * in Romania, ${header._count} ingredient lists, ${header._built}; ODbL 1.0), most frequent
 * first. Generated by
 * scripts/build-lexicon.mjs – do not edit by hand. Used by the OCR clean-up
 * (src/lib/lexicon.js), loaded with the photo reader only.
 */
export const LEXICON_RO_SOURCE = ${JSON.stringify({ lists: header._count, built: header._built })};
export const LEXICON_RO = ${JSON.stringify(words.join(' '))};
`;
writeFileSync(join(root, 'src', 'data', 'lexicon-ro.js'), out);
const withD = words.filter((w) => w !== normalize(w)).length;
console.log(`${words.length} words (${withD} with diacritics) from ${texts.length} lists → src/data/lexicon-ro.js (${(out.length / 1024).toFixed(1)} KB)`);
